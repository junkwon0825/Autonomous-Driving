% Basic assertions for all deterministic reference simulation scenarios.
projectRoot = fileparts(fileparts(mfilename('fullpath')));
addpath(fullfile(projectRoot, 'matlab'));

scenarios = lkas_scenarios();
assert(numel(scenarios) == 7, 'The reference suite must contain seven scenarios.');
results = cell(numel(scenarios), 1);
for k = 1:numel(scenarios)
    result = lkas_reference_simulation(scenarios(k));
    results{k} = result;
    assert(numel(result.time) > 1, 'Simulation must produce multiple samples.');
    assert(all(isfinite(result.lateralError)), 'Lateral error must remain finite.');
    assert(all(isfinite(result.headingError)), 'Heading error must remain finite.');
    assert(all(isfinite(result.yawRate)), 'Yaw rate must remain finite.');
    assert(all(isfinite(result.steeringAngle)), 'Steering command must remain finite.');
    assert(result.maxAbsSteeringAngle <= result.parameters.maxSteeringAngle + 1e-12, ...
        'Steering command exceeded the configured limit.');
end

assert(results{1}.rmsLateralError < abs(scenarios(1).initialLateralError), ...
    'Straight-road recovery did not reduce lateral-error RMS.');
assert(results{2}.rmsLateralError < 0.02, ...
    'Constant-curvature tracking error exceeded the test threshold.');
assert(results{4}.speed(end) > results{4}.speed(1), ...
    'Speed-ramp scenario did not increase speed.');
assert(any(results{5}.steeringAngle ~= results{7}.steeringAngle), ...
    'Noise-free comparison scenario must not match the noisy control output.');
assert(any(strcmp(results{6}.mode, 'TURN_SIGNAL_ACTIVE')), ...
    'Lane-change scenario is missing turn-signal state.');
assert(any(strcmp(results{6}.mode, 'LANE_CHANGE')), ...
    'Lane-change state was not entered.');
assert(any(strcmp(results{6}.mode, 'LANE_KEEPING_RESUME')), ...
    'Lane keeping was not resumed after the lane change.');
assert(any(results{6}.turnSignal), 'Turn-signal output was never active.');
assert(abs(results{6}.referenceLateralOffset(end) ...
    - scenarios(6).laneWidth) < 1e-12, ...
    'Lane-change reference did not reach the adjacent lane.');
assert(isnan(results{6}.settlingTime), ...
    'Lane-change transition must not report recovery settling time.');

fprintf('All %d LKAS reference scenario checks passed.\n', numel(scenarios));

summary = run_lkas_suite();
outputDirectory = fullfile(projectRoot, 'results', 'simulation');
savedMetrics = readtable(fullfile(outputDirectory, 'scenario_metrics.csv'));
savedSeries = readtable(fullfile(outputDirectory, 'scenario_timeseries.csv'));
savedBaseline = readtable(fullfile(outputDirectory, 'reference_simulation.csv'));
assert(height(savedMetrics) == numel(scenarios), ...
    'Saved metrics CSV does not contain one row per scenario.');
assert(height(savedSeries) == sum(cellfun(@(r) numel(r.time), results)), ...
    'Saved time-series CSV has an unexpected number of rows.');
assert(isequal(summary.scenario, savedMetrics.scenario), ...
    'Returned metrics and saved metrics CSV scenario order differ.');
assert(max(abs(summary.rms_lateral_error_m ...
    - savedMetrics.rms_lateral_error_m)) < 1e-12, ...
    'Saved RMS metrics do not match simulation output.');
assert(max(abs(summary.max_abs_lateral_error_m ...
    - savedMetrics.max_abs_lateral_error_m)) < 1e-12, ...
    'Saved maximum-error metrics do not match simulation output.');
assert(max(abs(summary.max_abs_heading_error_rad ...
    - savedMetrics.max_abs_heading_error_rad)) < 1e-12, ...
    'Saved heading metrics do not match simulation output.');
assert(max(abs(summary.max_abs_yaw_rate_rad_s ...
    - savedMetrics.max_abs_yaw_rate_rad_s)) < 1e-12, ...
    'Saved yaw-rate metrics do not match simulation output.');
assert(max(abs(summary.max_abs_steering_deg ...
    - savedMetrics.max_abs_steering_deg)) < 1e-12, ...
    'Saved steering metrics do not match simulation output.');

for k = 1:numel(scenarios)
    rows = strcmp(savedSeries.scenario, scenarios(k).name);
    assert(sum(rows) == numel(results{k}.time), ...
        'Saved time-series sample count differs from the simulated scenario.');
    assert(abs(sqrt(mean(savedSeries.lateral_error_m(rows).^2)) ...
        - savedMetrics.rms_lateral_error_m(k)) < 1e-12, ...
        'Saved RMS metric differs from the saved time series.');
    assert(abs(max(abs(savedSeries.lateral_error_m(rows))) ...
        - savedMetrics.max_abs_lateral_error_m(k)) < 1e-12, ...
        'Saved maximum lateral error differs from the saved time series.');
    assert(abs(max(abs(savedSeries.heading_error_rad(rows))) ...
        - savedMetrics.max_abs_heading_error_rad(k)) < 1e-12, ...
        'Saved heading metric differs from the saved time series.');
    assert(abs(max(abs(savedSeries.yaw_rate_rad_s(rows))) ...
        - savedMetrics.max_abs_yaw_rate_rad_s(k)) < 1e-12, ...
        'Saved yaw-rate metric differs from the saved time series.');
    assert(abs(max(abs(savedSeries.steering_angle_rad(rows))) * 180/pi ...
        - savedMetrics.max_abs_steering_deg(k)) < 1e-12, ...
        'Saved steering metric differs from the saved time series.');
    assert(abs(savedSeries.lateral_error_m(find(rows, 1, 'last')) ...
        - savedMetrics.final_lateral_error_m(k)) < 1e-12, ...
        'Saved final lateral error differs from the saved time series.');
end

baselineRows = strcmp(savedSeries.scenario, 'initial_offset');
assert(sum(baselineRows) == height(savedBaseline), ...
    'Reference-case CSV sample count does not match the scenario time series.');
assert(max(abs(savedSeries.time_s(baselineRows) ...
    - savedBaseline.time_s)) < 1e-12, ...
    'Reference-case timestamps differ between CSV files.');
assert(max(abs(savedSeries.lateral_error_m(baselineRows) ...
    - savedBaseline.lateral_error_m)) < 1e-12, ...
    'Reference-case CSV differs from scenario time-series CSV.');
assert(max(abs(savedSeries.heading_error_rad(baselineRows) ...
    - savedBaseline.heading_error_rad)) < 1e-12, ...
    'Reference-case heading CSV differs from scenario time-series CSV.');
assert(max(abs(savedSeries.yaw_rate_rad_s(baselineRows) ...
    - savedBaseline.yaw_rate_rad_s)) < 1e-12, ...
    'Reference-case yaw-rate CSV differs from scenario time-series CSV.');
assert(max(abs(savedSeries.steering_angle_rad(baselineRows) ...
    - savedBaseline.steering_angle_rad)) < 1e-12, ...
    'Reference-case steering CSV differs from scenario time-series CSV.');

negativeScenario = scenarios(1);
negativeScenario.name = 'negative_lateral_offset_check';
negativeScenario.initialLateralError = -negativeScenario.initialLateralError;
negativeScenario.initialHeadingError = -negativeScenario.initialHeadingError;
negativeResult = lkas_reference_simulation(negativeScenario);
assert(negativeResult.lateralOvershoot >= 0, ...
    'Overshoot calculation failed for a negative initial lateral error.');

run_lkas_demo();
comparisonImage = imfinfo(fullfile(outputDirectory, 'scenario_comparison.png'));
baselineImage = imfinfo(fullfile(outputDirectory, 'reference_simulation.png'));
assert(~isempty(comparisonImage) && ~isempty(baselineImage), ...
    'Simulation graphs were not generated.');
fprintf('Saved CSV values, sample counts, and graph outputs verified.\n');
